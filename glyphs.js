// Compose accented Latin letters from the original centerline and a matching mark.
// This keeps their size, spacing, and tracing style identical to unaccented letters.
(() => {
  const marks = {
    '\u0300': (x, y) => `M${x - .8} ${y - 1.5} L${x + .8} ${y}`,
    '\u0301': (x, y) => `M${x - .8} ${y} L${x + .8} ${y - 1.5}`,
    '\u0302': (x, y) => `M${x - 1.6} ${y} L${x} ${y - 1.5} L${x + 1.6} ${y}`,
    '\u0303': (x, y) => `M${x - 1.8} ${y} Q${x - 1} ${y - 1.5} ${x} ${y - .7} Q${x + 1} ${y + .1} ${x + 1.8} ${y - 1.4}`,
    '\u0304': (x, y) => `M${x - 1.6} ${y - .6} H${x + 1.6}`,
    '\u0306': (x, y) => `M${x - 1.6} ${y - 1.3} Q${x} ${y + .8} ${x + 1.6} ${y - 1.3}`,
    '\u0307': (x, y) => `M${x} ${y - .6} v.1`,
    '\u0308': (x, y) => `M${x - 1.2} ${y - .6} v.1 M${x + 1.2} ${y - .6} v.1`,
    '\u030a': (x, y) => `M${x} ${y - 1.8} C${x - 1.6} ${y - 1.8} ${x - 1.6} ${y + .2} ${x} ${y + .2} C${x + 1.6} ${y + .2} ${x + 1.6} ${y - 1.8} ${x} ${y - 1.8} Z`,
    '\u030c': (x, y) => `M${x - 1.6} ${y - 1.5} L${x} ${y} L${x + 1.6} ${y - 1.5}`,
    '\u0327': x => `M${x + .4} .2 L${x - .4} 1.2 Q${x + 1.2} 1 ${x + .9} 2.2 Q${x + .5} 3 ${x - .6} 2.5`
  };
  for (let code = 0x00c0; code <= 0x017f; code++) {
    const char = String.fromCodePoint(code);
    const [base, accent, extra] = Array.from(char.normalize('NFD'));
    const glyph = window.BlockGlyphs[base];
    if (!glyph || !marks[accent] || extra) continue;
    const [width, originalPath] = glyph;
    // The accent replaces the dot on lowercase i and j.
    const path = base === 'i' || base === 'j' ? originalPath.replace(/ M[^M]*$/, '') : originalPath;
    const accentY = base === base.toUpperCase() ? -11 : -7.5;
    window.BlockGlyphs[char] = [width, `${path} ${marks[accent](width / 2, accentY)}`];
  }
})();
